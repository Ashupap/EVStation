#!/usr/bin/env node
/**
 * Start/stop the full local development stack (see docs/RUNBOOK.md).
 *
 *   dev-stack.mjs up    start everything (creating .env from .env.example)
 *   dev-stack.mjs down  stop everything (volumes kept)
 *   dev-stack.mjs down --volumes   also remove data volumes
 *   dev-stack.mjs logs [service...]
 *
 * The Compose project name is pinned to `evstation` and the env file is
 * passed explicitly, so the scripts work from any working directory.
 */
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import net from 'node:net';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const composeDir = path.join(repoRoot, 'infra/compose');
const composeFile = path.join(composeDir, 'docker-compose.yml');
const envFile = path.join(composeDir, '.env');
const project = 'evstation';

const [, , command, ...args] = process.argv;

function composeArgs(extra) {
  // The Compose project directory is the directory of the -f file, so the
  // third_party/ relative mounts resolve correctly no matter the cwd.
  return [
    'compose',
    '--project-name',
    project,
    '--project-directory',
    composeDir,
    '--env-file',
    envFile,
    '-f',
    composeFile,
    ...extra,
  ];
}

function runCompose(extra, { capture = false } = {}) {
  const r = spawnSync('docker', composeArgs(extra), {
    stdio: capture ? ['ignore', 'pipe', 'inherit'] : 'inherit',
  });
  if (r.error) {
    console.error(`dev-stack: failed to run docker: ${r.error.message}`);
    process.exit(1);
  }
  if (r.status !== 0) {
    console.error(`dev-stack: docker compose failed (exit ${r.status})`);
    process.exit(r.status ?? 1);
  }
  return capture ? r.stdout.toString() : '';
}

function readEnvValues() {
  const vars = {};
  if (!fs.existsSync(envFile)) return vars;
  for (const line of fs.readFileSync(envFile, 'utf8').split('\n')) {
    const match = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
    if (match) vars[match[1]] = match[2].trim();
  }
  return vars;
}

function ensureDashboardEnv() {
  const vars = readEnvValues();
  const dashboardEnvFile = path.join(repoRoot, 'apps/dashboard/.env.local');
  const desired = {
    API_BASE_URL: 'http://localhost:4000',
    OIDC_ISSUER: 'http://localhost:8180/realms/evstation',
    OIDC_CLIENT_ID: 'dashboard',
    OIDC_CLIENT_SECRET: vars.KC_DASHBOARD_CLIENT_SECRET,
    OIDC_REDIRECT_URI: 'http://localhost:3200/auth/callback',
    SESSION_COOKIE_NAME: 'evstation_session',
    SESSION_ABSOLUTE_TTL_SECONDS: '28800',
    COOKIE_SECURE: 'false',
  };
  const exists = fs.existsSync(dashboardEnvFile);
  const current = exists ? fs.readFileSync(dashboardEnvFile, 'utf8') : '';
  const present = new Set(
    current
      .split('\n')
      .map((line) => line.match(/^([A-Za-z_][A-Za-z0-9_]*)=/)?.[1])
      .filter(Boolean),
  );
  const missing = Object.entries(desired).filter(([key, value]) => value && !present.has(key));
  if (exists && missing.length === 0) return;
  const body = missing.map(([key, value]) => `${key}=${value}`).join('\n');
  const header = exists
    ? '\n# Added by scripts/dev-stack.mjs for keys missing on upgrade.\n'
    : '# GENERATED by scripts/dev-stack.mjs; development only. Never commit.\n';
  fs.writeFileSync(dashboardEnvFile, `${current}${current ? header : header}${body}\n`);
  console.log('dev-stack: synced apps/dashboard/.env.local (values never printed)');
}

function ensureEnv() {
  // First-run creation or upgrade: generate random dev secrets instead of
  // committing fixed defaults. Existing keys are never rewritten; missing
  // keys are appended (e.g. new Phase 1 role/client secrets on an existing
  // checkout). The generated file is git-ignored; only its path is printed,
  // never the secret values (see .env.example for the variable map).
  const secret = () => crypto.randomBytes(18).toString('base64url');
  const defaults = {
    OUR_DB_PASSWORD: secret(),
    OUR_DB_OWNER_PASSWORD: secret(),
    OUR_DB_APP_PASSWORD: secret(),
    OUR_DB_INGEST_PASSWORD: secret(),
    OUR_DB_JOBS_PASSWORD: secret(),
    OUR_AMQP_WORKER_PASSWORD: secret(),
    KC_BOOTSTRAP_ADMIN_USERNAME: 'dev_admin',
    KC_BOOTSTRAP_ADMIN_PASSWORD: secret(),
    KC_DASHBOARD_CLIENT_SECRET: secret(),
    KC_CSMS_PROVISIONER_CLIENT_SECRET: secret(),
    KC_CSMS_READER_CLIENT_SECRET: secret(),
    DASHBOARD_SESSION_SECRET: secret(),
    HASURA_ADMIN_SECRET: secret(),
    CITRINE_HTTP_HOST_PORT: '8088',
    OUR_DB_HOST_PORT: '5432',
    KEYCLOAK_HTTP_HOST_PORT: '8180',
    KEYCLOAK_MGMT_HOST_PORT: '8181',
  };
  const exists = fs.existsSync(envFile);
  const current = exists ? fs.readFileSync(envFile, 'utf8') : '';
  const present = new Set(
    current
      .split('\n')
      .map((line) => line.match(/^([A-Za-z_][A-Za-z0-9_]*)=/)?.[1])
      .filter(Boolean),
  );
  const missing = Object.entries(defaults).filter(([key]) => !present.has(key));
  if (exists && missing.length === 0) return;

  const header = exists
    ? '\n# Added by scripts/dev-stack.mjs for keys missing on upgrade.\n'
    : [
        '# GENERATED by scripts/dev-stack.mjs (pnpm dev:stack) on first run.',
        '# Development-only values; never commit this file.',
      ].join('\n');
  const body = missing.map(([key, value]) => `${key}=${value}`).join('\n');
  fs.writeFileSync(envFile, `${current}${current ? header : `${header}\n`}${body}\n`);
  console.log(
    `dev-stack: ${exists ? 'added missing keys to' : 'created'} infra/compose/.env with RANDOM dev secrets ` +
      '(path logged here; secret values never printed — see infra/compose/.env.example).',
  );
}

// ---------------------------------------------------------------------------
// Port availability pre-check (ADR-0007): fail fast with an actionable
// message when any host port we are about to bind is already taken. We never
// kill processes; the operator stops the conflicting process or changes the
// variable. Ports 8080/3000 are permanently reserved on this host and are
// NOT checked (the stack must not bind them anywhere).
// ---------------------------------------------------------------------------

function readEnvFile() {
  const vars = {};
  if (!fs.existsSync(envFile)) return vars;
  for (const line of fs.readFileSync(envFile, 'utf8').split('\n')) {
    const m = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
    if (m) vars[m[1]] = m[2].trim();
  }
  return vars;
}

const CONFIGURABLE_PORT_VARS = [
  ['OUR_DB_HOST_PORT', 'our PostGIS database'],
  ['KEYCLOAK_HTTP_HOST_PORT', 'Keycloak HTTP'],
  ['KEYCLOAK_MGMT_HOST_PORT', 'Keycloak management'],
  ['CITRINE_HTTP_HOST_PORT', 'CitrineOS HTTP + Swagger'],
];

const FIXED_HOST_PORTS = [
  [8081, 'CitrineOS OCPP WebSocket profile 0 (no auth)'],
  [8082, 'CitrineOS OCPP WebSocket profile 1'],
  [8443, 'CitrineOS OCPP WebSocket profile 2 (TLS)'],
  [8444, 'CitrineOS OCPP WebSocket profile 3 (mTLS)'],
  [9229, 'CitrineOS Node.js debugger'],
  [15432, "CitrineOS's own database (ocpp-db)"],
  [8090, 'Hasura GraphQL engine'],
  [5672, 'RabbitMQ AMQP'],
  [15672, 'RabbitMQ management'],
];

function portAvailable(port) {
  return new Promise((resolve) => {
    const socket = new net.Socket();
    const done = (ok) => {
      socket.destroy();
      resolve(ok);
    };
    socket.setTimeout(750);
    socket.once('connect', () => done(false));
    socket.once('timeout', () => done(true));
    socket.once('error', () => done(true));
    socket.connect(port, '127.0.0.1');
  });
}

async function checkHostPorts(wantUi) {
  const vars = readEnvFile();
  const problems = [];
  for (const [name, what] of CONFIGURABLE_PORT_VARS) {
    const port = Number.parseInt(vars[name], 10);
    if (!Number.isInteger(port)) continue; // compose uses its default
    if (await portAvailable(port)) continue;
    problems.push(
      `  host port ${port} (${what}) is already in use — set ${name}=<free port> in infra/compose/.env (see docs/RUNBOOK.md)`,
    );
  }
  for (const [port, what] of FIXED_HOST_PORTS) {
    if (await portAvailable(port)) continue;
    problems.push(
      `  host port ${port} (${what}) is already in use — it is a fixed ` +
        `mapping in infra/compose/docker-compose.yml; stop the conflicting ` +
        `process (never kill it ourselves) or edit the mapping there`,
    );
  }
  if (wantUi) {
    if (!(await portAvailable(13000))) {
      problems.push(
        '  host port 13000 (CitrineOS Operator UI) is already in use — fixed mapping in infra/compose/docker-compose.yml',
      );
    }
  }
  const reserves =
    '  (informational: 3200 dashboard and 4000 API are reserved for Phase 1; ' +
    '8080/3000 are permanently reserved on this host and never used here)';
  if (problems.length) {
    console.error('dev-stack: PORT CONFLICT(S) — nothing started:');
    for (const p of problems) console.error(p);
    console.error(reserves);
    process.exit(1);
  }
  console.log('dev-stack: port pre-check OK (all published host ports free)');
  console.log(reserves);
}

async function stackRunning() {
  const r = spawnSync('docker', composeArgs(['ps', '--status=running', '-q']), {
    stdio: ['ignore', 'pipe', 'inherit'],
  });
  if (r.status !== 0) return false;
  return r.stdout.toString().trim().length > 0;
}

switch (command) {
  case 'up': {
    ensureEnv();
    // Validate the merged config before touching Docker.
    spawnSync('docker', composeArgs(['config', '--quiet']), { stdio: 'inherit' });
    if (!(await stackRunning())) {
      await checkHostPorts(args.includes('--ui'));
    }
    console.log('dev-stack: starting stack (images pull on first run)…');
    const upExtra = args.includes('--ui') ? ['--profile', 'ui'] : [];
    runCompose(['up', '-d', '--wait', '--wait-timeout', '600', ...upExtra]);
    const seed = spawnSync(process.execPath, [path.join(repoRoot, 'scripts/seed-keycloak.mjs')], {
      stdio: 'inherit',
    });
    if (seed.status !== 0) {
      console.error('dev-stack: Keycloak client seeding failed');
      process.exit(seed.status ?? 1);
    }
    const overlay = spawnSync(
      process.execPath,
      [path.join(repoRoot, 'scripts/apply-hasura-overlay.mjs')],
      {
        stdio: 'inherit',
      },
    );
    if (overlay.status !== 0) {
      console.error('dev-stack: Hasura adapter overlay failed');
      process.exit(overlay.status ?? 1);
    }
    const amqp = spawnSync(process.execPath, [path.join(repoRoot, 'scripts/provision-amqp.mjs')], {
      stdio: 'inherit',
    });
    if (amqp.status !== 0) {
      console.error('dev-stack: AMQP ingestion provisioning failed');
      process.exit(amqp.status ?? 1);
    }
    ensureDashboardEnv();
    console.log('dev-stack: stack is up. See docs/RUNBOOK.md for the port map.');
    break;
  }
  case 'down': {
    const extra = args.includes('--volumes') ? ['-v'] : [];
    runCompose(['down', '--remove-orphans', ...extra]);
    if (!extra.length) {
      console.log('dev-stack: stopped (data volumes kept). Run down --volumes to wipe data.');
    }
    break;
  }
  case 'logs': {
    runCompose(['logs', '--tail=100', '-f', ...args]);
    break;
  }
  default: {
    console.error('usage: dev-stack.mjs up | down [--volumes] | logs [service…]');
    process.exit(1);
  }
}
